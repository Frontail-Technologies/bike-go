import { readdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import process from "node:process";
import ts from "typescript";

const args = process.argv.slice(2);
const CHECK = args.includes("--check");
const roots = args.filter((arg) => !arg.startsWith("--"));
if (roots.length === 0) roots.push("src");

const CODE = new Set([".ts", ".tsx", ".js", ".jsx", ".mjs", ".cjs"]);
const SKIP_DIRS = new Set(["node_modules", ".next", ".git", "dist", "build", "out"]);
const KEEP = /^\/\/\s*Generated by |eslint-(disable|enable)|@ts-(expect-error|ignore|nocheck|check)|^\/\/\/\s*<reference|webpackChunkName|#__PURE__|@__PURE__|prettier-ignore|@vite-ignore/;

async function* walk(target) {
  const entries = await readdir(target, { withFileTypes: true }).catch(() => null);
  if (!entries) {
    yield target;
    return;
  }
  for (const entry of entries) {
    if (entry.isDirectory()) {
      if (!SKIP_DIRS.has(entry.name) && !entry.name.startsWith(".next")) yield* walk(path.join(target, entry.name));
    } else yield path.join(target, entry.name);
  }
}

const scriptKind = (file) => (file.endsWith(".tsx") || file.endsWith(".jsx") ? ts.ScriptKind.TSX : file.endsWith(".ts") ? ts.ScriptKind.TS : ts.ScriptKind.JS);

function codeCommentRanges(file, text) {
  const source = ts.createSourceFile(file, text, ts.ScriptTarget.Latest, true, scriptKind(file));
  const ranges = new Map();
  const add = (list) => list?.forEach((range) => ranges.set(range.pos, range));
  const emptyJsx = [];

  const visit = (node) => {
    if (node.kind === ts.SyntaxKind.JsxText) return;
    if (ts.isJsxExpression(node) && !node.expression) emptyJsx.push({ pos: node.getStart(source), end: node.end });
    const children = node.getChildren(source);
    if (children.length === 0) {
      add(ts.getLeadingCommentRanges(text, node.getFullStart()));
      add(ts.getTrailingCommentRanges(text, node.end));
      return;
    }
    let previous;
    for (const child of children) {
      // JSX text holds whitespace and characters such as // as content, not trivia.
      if (child.kind !== ts.SyntaxKind.JsxText && previous?.kind !== ts.SyntaxKind.JsxText) add(ts.getLeadingCommentRanges(text, child.getFullStart()));
      visit(child);
      previous = child;
    }
  };
  visit(source);
  add(ts.getLeadingCommentRanges(text, source.endOfFileToken.getFullStart()));

  const comments = [...ranges.values()].filter((range) => !KEEP.test(text.slice(range.pos, range.end)));
  // `{/* note */}` in JSX leaves an empty `{}` behind once its comment goes, so drop the whole container.
  const containers = emptyJsx.filter((jsx) => {
    const inner = comments.filter((range) => range.pos >= jsx.pos && range.end <= jsx.end);
    return inner.length > 0 && text.slice(jsx.pos + 1, jsx.end - 1).replace(/\/\*[\s\S]*?\*\/|\/\/[^\n]*/g, "").trim() === "";
  });
  return [...containers, ...comments.filter((range) => !containers.some((jsx) => range.pos >= jsx.pos && range.end <= jsx.end))];
}

function cssCommentRanges(text) {
  const ranges = [];
  let quote = null;
  for (let i = 0; i < text.length; i++) {
    const char = text[i];
    if (quote) {
      if (char === "\\") i++;
      else if (char === quote) quote = null;
    } else if (char === '"' || char === "'") quote = char;
    else if (char === "/" && text[i + 1] === "*") {
      const end = text.indexOf("*/", i + 2);
      const stop = end === -1 ? text.length : end + 2;
      if (!KEEP.test(text.slice(i, stop))) ranges.push({ pos: i, end: stop });
      i = stop - 1;
    }
  }
  return ranges;
}

function remove(text, ranges) {
  let out = text;
  for (const { pos, end } of [...ranges].sort((a, b) => b.pos - a.pos)) {
    const lineStart = out.lastIndexOf("\n", pos - 1) + 1;
    const nextNewline = out.indexOf("\n", end);
    const lineEnd = nextNewline === -1 ? out.length : nextNewline;
    const before = out.slice(lineStart, pos);
    const after = out.slice(end, lineEnd).replace(/\r$/, "");
    if (before.trim() === "" && after.trim() === "") {
      // The comment was alone on its line(s): remove the line(s) entirely.
      out = out.slice(0, lineStart) + out.slice(nextNewline === -1 ? out.length : nextNewline + 1);
    } else if (after.trim() === "") {
      out = out.slice(0, pos).replace(/[ \t]+$/, "") + out.slice(end);
    } else {
      // Mid-line comment: keep one space where it separated words, never glue two identifiers together.
      const left = out.slice(0, pos);
      const right = out.slice(end);
      if (/^[)\]},;]/.test(right)) out = left.replace(/[ \t]+$/, "") + right;
      else if (/[ \t]$/.test(left) && /^[ \t]/.test(right)) out = left + right.replace(/^[ \t]+/, "");
      else if (/[\w$]$/.test(left) && /^[\w$]/.test(right)) out = `${left} ${right}`;
      else out = left + right;
    }
  }
  return out.replace(/(\r?\n)(?:[ \t]*\r?\n){2,}/g, "$1$1");
}

const printer = ts.createPrinter({ removeComments: true });
const shape = (file, text) => printer.printFile(ts.createSourceFile(file, text, ts.ScriptTarget.Latest, true, scriptKind(file))).replace(/\s+/g, " ").trim();

let changed = 0;
const pending = [];
for (const root of roots) {
  for await (const file of walk(root)) {
    const ext = path.extname(file);
    if (!CODE.has(ext) && ext !== ".css") continue;
    const text = await readFile(file, "utf8");
    const ranges = ext === ".css" ? cssCommentRanges(text) : codeCommentRanges(file, text);
    if (ranges.length === 0) continue;
    const next = remove(text, ranges);
    if (next === text) continue;
    if (ext !== ".css" && shape(file, text) !== shape(file, next)) {
      process.stderr.write(`skipped ${file}: removing its comments would change the code\n`);
      process.exitCode = 1;
      continue;
    }
    if (CHECK) pending.push(file);
    else {
      await writeFile(file, next, "utf8");
      changed++;
    }
  }
}

if (CHECK) {
  if (pending.length) {
    process.stderr.write(`Comments found in:\n${pending.map((file) => `- ${file}`).join("\n")}\n`);
    process.exitCode = 1;
  }
} else process.stdout.write(`stripped comments from ${changed} file(s)\n`);
