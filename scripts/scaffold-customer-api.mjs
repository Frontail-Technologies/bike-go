import { mkdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import process from "node:process";
import { fileURLToPath } from "node:url";
import { customerApiManifest } from "./customer-api-manifest.mjs";

const ROOT = process.cwd();
const CHECK = process.argv.includes("--check");
const METHODS = new Set(["GET", "POST", "PUT", "PATCH", "DELETE"]);
const GENERATED = "// Generated by scripts/scaffold-customer-api.mjs. Do not edit by hand.\n";

export const artifactNames = (feature) => ({
  api: `${feature.domain}-api.ts`,
  hooks: `use-${feature.domain}.ts`,
  keys: "query-keys.ts",
});

export const pathParams = (route) => [...route.matchAll(/:([A-Za-z][A-Za-z0-9_]*)/g)].map((match) => match[1]);
const typeNames = (operations) => [...new Set(operations.flatMap((operation) => [operation.queryType, operation.bodyType, operation.responseType]).filter(Boolean))].sort();
const queryTypeNames = (operations) => [...new Set(operations.map((operation) => operation.queryType).filter(Boolean))].sort();
const routeExpression = (route) => {
  const params = pathParams(route);
  if (!params.length) return JSON.stringify(route);
  return `\`${route.replace(/:([A-Za-z][A-Za-z0-9_]*)/g, "${encodeURIComponent($1)}")}\``;
};
const paramSignature = (operation) => [
  ...pathParams(operation.path).map((name) => `${name}: string`),
  ...(operation.queryType ? [`params: ${operation.queryType}`] : []),
  ...(operation.bodyType ? [`input: ${operation.bodyType}`] : []),
];

export function validateManifest(manifest = customerApiManifest) {
  const domains = new Set();
  for (const feature of manifest) {
    if (domains.has(feature.domain)) throw new Error(`Duplicate customer API domain: ${feature.domain}`);
    domains.add(feature.domain);
    const normalized = path.normalize(feature.featureDir);
    if (path.isAbsolute(normalized) || normalized.startsWith("..") || !normalized.startsWith(`src${path.sep}features${path.sep}customer${path.sep}`)) {
      throw new Error(`Unsafe feature directory: ${feature.featureDir}`);
    }
    const names = new Set();
    for (const operation of feature.operations) {
      if (names.has(operation.name)) throw new Error(`Duplicate operation ${feature.domain}.${operation.name}`);
      names.add(operation.name);
      if (!METHODS.has(operation.method)) throw new Error(`Invalid method ${operation.method} for ${feature.domain}.${operation.name}`);
      if (!operation.path.startsWith("/")) throw new Error(`API path must start with / for ${feature.domain}.${operation.name}`);
      if (!operation.responseType) throw new Error(`Missing responseType for ${feature.domain}.${operation.name}`);
      if (operation.kind !== "query" && operation.kind !== "mutation") throw new Error(`Invalid operation kind for ${feature.domain}.${operation.name}`);
    }
  }
}

export function apiFile(feature) {
  const types = typeNames(feature.operations);
  const hasPage = feature.operations.some((operation) => operation.paginated);
  const functions = feature.operations.map((operation) => {
    const args = paramSignature(operation);
    if (operation.kind === "query") args.push("signal?: AbortSignal");
    const config = [
      `method: ${JSON.stringify(operation.method)}`,
      `url: ${routeExpression(operation.path)}`,
      operation.queryType ? "params" : null,
      operation.bodyType ? "data: input" : null,
      operation.kind === "query" ? "signal" : null,
      operation.idempotency ? 'headers: options?.idempotencyKey ? { "Idempotency-Key": options.idempotencyKey } : undefined' : null,
    ].filter(Boolean).join(", ");
    if (operation.idempotency) args.push("options?: { idempotencyKey?: string }");
    const returnType = operation.paginated ? `ApiPage<${operation.responseType}>` : operation.array ? `${operation.responseType}[]` : operation.responseType;
    const envelopeType = operation.paginated || operation.array ? `${operation.responseType}[]` : operation.responseType;
    const unwrap = operation.paginated ? "unwrapPage" : "unwrapData";
    return `export async function ${operation.name}(${args.join(", ")}): Promise<${returnType}> {\n  const response = await apiClient.request<ApiEnvelope<${envelopeType}>>({ ${config} });\n  return ${unwrap}(response.data);\n}`;
  }).join("\n\n");
  return `${GENERATED}\nimport { apiClient } from "@/lib/api/client";\nimport { unwrapData${hasPage ? ", unwrapPage" : ""}, type ApiEnvelope${hasPage ? ", type ApiPage" : ""} } from "@/lib/api/contracts";${types.length ? `\nimport type { ${types.join(", ")} } from "../types";` : ""}\n\n${functions}\n`;
}

export function keysFile(feature) {
  const queryTypes = queryTypeNames(feature.operations);
  const entries = feature.operations.filter((operation) => operation.kind === "query").map((operation) => {
    const args = [...pathParams(operation.path).map((name) => `${name}: string`), ...(operation.queryType ? [`params: ${operation.queryType}`] : [])];
    const values = [...pathParams(operation.path), ...(operation.queryType ? ["params"] : [])];
    return `  ${operation.name}: (${args.join(", ")}) => [...${feature.keyName}.root(), ${JSON.stringify(operation.name)}${values.length ? `, ${values.join(", ")}` : ""}] as const,`;
  }).join("\n");
  return `${GENERATED}${queryTypes.length ? `\nimport type { ${queryTypes.join(", ")} } from "./types";\n` : "\n"}\nexport const ${feature.keyName} = {\n  root: () => ["customer", ${JSON.stringify(feature.domain)}] as const,\n${entries}\n} as const;\n`;
}

export function hooksFile(feature) {
  const artifacts = artifactNames(feature);
  const types = [...new Set(feature.operations.flatMap((operation) => [operation.queryType, operation.bodyType]).filter(Boolean))].sort();
  const hasPage = feature.operations.some((operation) => operation.paginated);
  const hasQuery = feature.operations.some((operation) => operation.kind === "query");
  const hasMutation = feature.operations.some((operation) => operation.kind === "mutation");
  const reactQueryImports = [hasPage ? "keepPreviousData" : null, hasMutation ? "useMutation" : null, hasQuery ? "useQuery" : null, hasMutation ? "useQueryClient" : null].filter(Boolean).join(", ");
  const hooks = feature.operations.map((operation) => {
    const params = pathParams(operation.path);
    if (operation.kind === "query") {
      const signature = [...params.map((name) => `${name}: string`), ...(operation.queryType ? [`params: ${operation.queryType}`] : [])];
      const callArgs = [...params, ...(operation.queryType ? ["params"] : []), "signal"];
      const keyArgs = [...params, ...(operation.queryType ? ["params"] : [])];
      const options = [
        `queryKey: ${feature.keyName}.${operation.name}(${keyArgs.join(", ")})`,
        `queryFn: ({ signal }) => api.${operation.name}(${callArgs.join(", ")})`,
        operation.paginated ? "placeholderData: keepPreviousData" : null,
        params.length ? `enabled: ${params.map((name) => `Boolean(${name})`).join(" && ")}` : null,
      ].filter(Boolean).join(",\n    ");
      return `export function ${operation.hook}(${signature.join(", ")}) {\n  return useQuery({\n    ${options},\n  });\n}`;
    }

    const variableFields = [...params.map((name) => `${name}: string`), ...(operation.bodyType ? [`input: ${operation.bodyType}`] : []), ...(operation.idempotency ? ["idempotencyKey?: string"] : [])];
    const signature = variableFields.length ? `{ ${variableFields.join("; ")} }` : "void";
    const variableAccess = [...params.map((name) => `variables.${name}`), ...(operation.bodyType ? ["variables.input"] : []), ...(operation.idempotency ? ["{ idempotencyKey: variables.idempotencyKey }"] : [])];
    return `export function ${operation.hook}() {\n  const queryClient = useQueryClient();\n  return useMutation({\n    mutationFn: (variables: ${signature}) => api.${operation.name}(${variableAccess.join(", ")}),\n    onSuccess: () => queryClient.invalidateQueries({ queryKey: ${feature.keyName}.root() }),\n  });\n}`;
  }).join("\n\n");
  return `${GENERATED}\n"use client";\n\nimport { ${reactQueryImports} } from "@tanstack/react-query";\nimport * as api from "../api/${artifacts.api.replace(/\.ts$/, "")}";\nimport { ${feature.keyName} } from "../${artifacts.keys.replace(/\.ts$/, "")}";${types.length ? `\nimport type { ${types.join(", ")} } from "../types";` : ""}\n\n${hooks}\n`;
}

async function syncFile(file, content, stale) {
  let existing = null;
  try { existing = await readFile(file, "utf8"); } catch (error) { if (error?.code !== "ENOENT") throw error; }
  if (existing === content) return;
  if (CHECK) { stale.push(path.relative(ROOT, file)); return; }
  await mkdir(path.dirname(file), { recursive: true });
  await writeFile(file, content, "utf8");
  process.stdout.write(`generated ${path.relative(ROOT, file)}\n`);
}

export async function scaffoldCustomerApi() {
  validateManifest();
  const stale = [];
  for (const feature of customerApiManifest) {
    const directory = path.resolve(ROOT, feature.featureDir);
    const artifacts = artifactNames(feature);
    await syncFile(path.join(directory, "api", artifacts.api), apiFile(feature), stale);
    await syncFile(path.join(directory, artifacts.keys), keysFile(feature), stale);
    await syncFile(path.join(directory, "hooks", artifacts.hooks), hooksFile(feature), stale);
  }
  if (stale.length) {
    process.stderr.write(`Generated customer API files are stale:\n${stale.map((file) => `- ${file}`).join("\n")}\n`);
    process.exitCode = 1;
  }
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) await scaffoldCustomerApi();
